import fs from "node:fs"
import path from "node:path"
import { html, json, readBody } from "../../../http.mjs"
import { sendNotFound } from "../../../not-found-page.mjs"
import { contentTypeFor } from "../../../util.mjs"
import { cleanPath, matchDeclaredRoute } from "../runner.mjs"
import { resolveUiAsset, uiFallbackHtml } from "../ui-scaffold.mjs"

/** Mirrors the platform's secret mask for `type: "secret"` config fields. */
const SECRET_MASK = "••••••••"

const UI_CSP = [
  "default-src 'self' data: blob:",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-ancestors 'self'",
].join("; ")

/**
 * The platform-shaped tail of the dev server: the dev `files/` store, the kit
 * runtime's `/api/plugins/:slug/(config|jobs)` endpoints, plugin UI assets and
 * the plugin's own `apiRoutes`/`publicRoutes`. Ends with the styled 404 for
 * anything else, so this handler is always terminal.
 *
 * Returns a `handle(req, res, url)` that always resolves `true`.
 */
export function createPlatformRoutes({
  projectId,
  devDir,
  manifestStore,
  state,
  applySettings,
  log,
  mockJobs,
  runMockJob,
  tickMockJob,
  runner,
  ctx,
  getUiDir,
}) {
  return async function handle(req, res, url) {
    const pathname = url.pathname

    if (req.method === "GET" && pathname.startsWith("/__dev/files/")) {
      const key = decodeURIComponent(pathname.slice("/__dev/files/".length))
      const file = path.resolve(path.join(devDir, "files"), key)
      const root = path.resolve(path.join(devDir, "files"))
      if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
        json(res, 404, { error: "File not found" })
        return true
      }
      res.writeHead(200, { "Content-Type": contentTypeFor(file), "Cache-Control": "no-store" })
      res.end(fs.readFileSync(file))
      return true
    }

    // ── Platform-shaped endpoints for the compiled kit runtime ────────────
    // Kit pages (generated by the SDK into ui/kit/) call the same host APIs
    // the platform serves, so the preview exercises the real renderer.
    const kitMatch = /^\/api\/plugins\/([^/]+)\/(config|jobs)(\/[^/]*)?(\/tick)?$/.exec(pathname)
    if (kitMatch) {
      const manifest = manifestStore.read()
      if (kitMatch[1] !== manifest.slug) {
        json(res, 404, { error: `Only "${manifest.slug}" runs in this dev server` })
        return true
      }
      const kind = kitMatch[2]
      const tail = `${kitMatch[3] ?? ""}${kitMatch[4] ?? ""}`
      if (kind === "config") {
        const secretKeys = new Set(
          (manifest.configSchema ?? []).filter((field) => field?.type === "secret").map((field) => field.key),
        )
        const maskedConfig = () => {
          const values = { ...state.settings() }
          for (const key of secretKeys) if (values[key]) values[key] = SECRET_MASK
          return values
        }
        if (req.method === "GET") {
          json(res, 200, {
            plugin: {
              slug: manifest.slug,
              name: manifest.name,
              version: manifest.version,
              configSchema: manifest.configSchema ?? [],
              jobs: manifest.jobs ?? [],
            },
            enabled: true,
            config: maskedConfig(),
          })
          return true
        }
        if (req.method === "PUT") {
          const body = await readBody(req)
          // Mirrors the platform: masked/blank secrets keep their stored
          // value, everything else merges over the previous settings.
          const next = { ...state.settings() }
          for (const [key, value] of Object.entries(body?.config ?? {})) {
            if (secretKeys.has(key) && (value === SECRET_MASK || value === "" || value === null || value === undefined)) continue
            next[key] = value
          }
          applySettings(next)
          log("settings saved (merged into ctx.config)")
          json(res, 200, { config: maskedConfig() })
          return true
        }
        json(res, 405, { error: "Method not allowed" })
        return true
      }
      // Jobs API — mirrors the platform's plugin job endpoints.
      const jobMatch = /^\/(\d+)(\/tick)?$/.exec(tail)
      // `checkpoint` is the paused-run state the server holds internally —
      // clients never see it (same as items/logs on list responses).
      const publicJob = (entry) => {
        const { items, logs, checkpoint, ...rest } = entry
        return rest
      }
      if (!tail) {
        if (req.method === "GET") {
          json(res, 200, {
            jobs: mockJobs.slice(-10).reverse().map(publicJob),
          })
          return true
        }
        if (req.method === "POST") {
          const body = await readBody(req)
          try {
            const job = await runMockJob({ type: String(body?.type ?? ""), input: body?.input ?? {}, maxTicks: body?.maxTicks })
            json(res, 200, { job: publicJob(job) })
          } catch (error) {
            json(res, 500, { error: error.message })
          }
          return true
        }
        json(res, 405, { error: "Method not allowed" })
        return true
      }
      if (jobMatch) {
        const row = mockJobs.find((entry) => entry.id === Number(jobMatch[1]))
        if (!row) {
          json(res, 404, { error: "Job not found" })
          return true
        }
        // A tick continues a paused job from its checkpoint; finished or
        // unknown jobs tick as a no-op, like on the platform.
        if (jobMatch[2]) {
          if (req.method === "POST") {
            const job = await tickMockJob(row)
            json(res, 200, { job: publicJob(job) })
            return true
          }
          json(res, 405, { error: "Method not allowed" })
          return true
        }
        if (req.method === "GET") {
          json(res, 200, { job: publicJob(row), items: row.items ?? [], logs: row.logs ?? [] })
          return true
        }
        json(res, 405, { error: "Method not allowed" })
        return true
      }
      json(res, 404, { error: "Not found" })
      return true
    }

    // ── Plugin UI assets (dashboard + public) ──────────────────────────────
    const uiMatch = /^\/api\/(?:plugins|plugin-public)\/([^/]+)\/ui\/(.*)$/.exec(pathname)
    if (req.method === "GET" && uiMatch) {
      const [, slug, ...rest] = uiMatch
      const manifest = manifestStore.read()
      if (slug !== manifest.slug) {
        json(res, 404, { error: `Only "${manifest.slug}" runs in this dev server` })
        return true
      }
      const requested = decodeURIComponent(rest.join("/"))
      // The Settings dialog preview appends ?dialog=settings — the fallback
      // wording follows the surface the iframe is trying to render.
      const context = url.searchParams.get("dialog") === "settings" ? "settings" : "dashboard"
      const fallback = (reason) =>
        html(
          res,
          404,
          uiFallbackHtml({
            title: manifest.ui?.title ?? manifest.name,
            entry: reason === "missing" ? requested : null,
            reason,
            slug: manifest.slug,
            context,
          }),
        )
      const uiDir = getUiDir()
      if (!uiDir) {
        fallback("no-ui")
        return true
      }
      const file = resolveUiAsset(uiDir, requested)
      if (!file) {
        fallback("missing")
        return true
      }
      res.writeHead(200, {
        "Content-Type": contentTypeFor(file),
        "Content-Security-Policy": UI_CSP,
        "Cache-Control": "no-store",
        "X-Content-Type-Options": "nosniff",
      })
      res.end(fs.readFileSync(file))
      return true
    }

    // ── Plugin API routes ───────────────────────────────────────────────────
    const apiMatch = /^\/api\/(plugin-api|plugin-public)\/([^/]+)(\/.*)?$/.exec(pathname)
    if (apiMatch) {
      const manifest = manifestStore.read()
      const kind = apiMatch[1] === "plugin-public" ? "public" : "authenticated"
      const [, , slug, tail] = apiMatch
      if (slug !== manifest.slug) {
        json(res, 404, { error: `Only "${manifest.slug}" runs in this dev server` })
        return true
      }
      const requestPath = cleanPath(tail ?? "/")
      const declaredList = kind === "public" ? (manifest.publicRoutes ?? []) : (manifest.apiRoutes ?? [])
      // Exact path wins, then `:param` patterns, then the longest declared
      // prefix (so a short route never swallows its own sub-paths).
      const matched = matchDeclaredRoute(declaredList, requestPath)
      if (!matched) {
        json(res, 404, { error: `No ${kind} route "${requestPath}" declared in plugin.json` })
        return true
      }
      const { route: match, params } = matched
      const methods = (match.methods ?? ["GET"]).map((method) => method.toUpperCase())
      if (!methods.includes(req.method)) {
        json(res, 405, { error: `Method ${req.method} not allowed for ${match.path}` })
        return true
      }
      const body = req.method === "GET" || req.method === "HEAD" ? null : await readBody(req)
      const query = Object.fromEntries(url.searchParams.entries())
      try {
        const started = Date.now()
        const result = await runner.invokeRoute(
          match.path,
          { method: req.method, path: requestPath, params, query, body },
          ctx,
          kind,
        )
        state.record("routes", { path: requestPath })
        log(`${req.method} ${requestPath} → ${Date.now() - started}ms`)
        if (result && typeof result === "object" && "status" in result && "body" in result) {
          json(res, Number(result.status) || 200, result.body)
          return true
        }
        json(res, 200, result ?? null)
      } catch (error) {
        log(`${req.method} ${requestPath} → error: ${error.message}`)
        json(res, 500, { error: error.message })
      }
      return true
    }

    // Unknown path: styled page for browser navigations, JSON for API clients.
    sendNotFound(req, res, {
      pathname,
      homeUrl: `/${projectId}`,
      homeLabel: "Back to the preview",
      hint: "Preview pages live under this project's id — pick one from the sidebar, or press Ctrl+K for the command palette.",
      links: [
        { to: `/${projectId}`, label: "Overview" },
        { to: `/${projectId}/code`, label: "Code" },
        { to: `/${projectId}/console`, label: "Console" },
        { to: `/${projectId}/settings`, label: "Settings" },
      ],
    })
    return true
  }
}
